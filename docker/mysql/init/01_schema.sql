-- COLEGIO_APPCOL schema (MySQL 8) — corregido vs modelo MWB
CREATE DATABASE IF NOT EXISTS COLEGIO_APPCOL
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE COLEGIO_APPCOL;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS Asistencia;
DROP TABLE IF EXISTS Notas;
DROP TABLE IF EXISTS Pagos;
DROP TABLE IF EXISTS Horarios;
DROP TABLE IF EXISTS Matriculas;
DROP TABLE IF EXISTS Materia;
DROP TABLE IF EXISTS Usuarios;
DROP TABLE IF EXISTS Alumnos;
DROP TABLE IF EXISTS Profesores;
DROP TABLE IF EXISTS Curso;

SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE Profesores (
  idPROFESORES INT NOT NULL AUTO_INCREMENT,
  NOMBRE VARCHAR(50) NOT NULL,
  APELLIDO VARCHAR(50) NOT NULL,
  CORREO VARCHAR(100) NOT NULL,
  TELEFONO VARCHAR(20) NULL,
  ESPECIALIDAD VARCHAR(100) NULL,
  PRIMARY KEY (idPROFESORES),
  UNIQUE KEY uk_profesores_correo (CORREO)
) ENGINE=InnoDB;

CREATE TABLE Alumnos (
  idAlumnos INT NOT NULL AUTO_INCREMENT,
  NOMBRE VARCHAR(50) NOT NULL,
  APELLIDO VARCHAR(50) NOT NULL,
  FECHA_NACIMIENTO DATE NULL,
  DIRECCION TEXT NULL,
  TELEFONO VARCHAR(20) NULL,
  GRADO_ACTUAL VARCHAR(20) NULL,
  NOMBRE_ACUDIENTE VARCHAR(100) NULL,
  TELEFONO_ACUDIENTE VARCHAR(20) NULL,
  ANO_ACTUAL VARCHAR(8) NULL,
  PRIMARY KEY (idAlumnos)
) ENGINE=InnoDB;

CREATE TABLE Curso (
  idCurso INT NOT NULL AUTO_INCREMENT,
  Grado VARCHAR(20) NOT NULL,
  Jornada VARCHAR(20) NOT NULL,
  Nivel VARCHAR(30) NOT NULL,
  Capacidad INT NOT NULL DEFAULT 30,
  PRIMARY KEY (idCurso)
) ENGINE=InnoDB;

CREATE TABLE Materia (
  idMateria INT NOT NULL AUTO_INCREMENT,
  Codigo VARCHAR(20) NOT NULL,
  Nombre VARCHAR(100) NOT NULL,
  ID_Profesor INT NULL,
  PRIMARY KEY (idMateria),
  UNIQUE KEY uk_materia_codigo (Codigo),
  CONSTRAINT fk_materia_profesor
    FOREIGN KEY (ID_Profesor) REFERENCES Profesores (idPROFESORES)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE Matriculas (
  idMatriculas INT NOT NULL AUTO_INCREMENT,
  ID_Estudiante INT NOT NULL,
  ID_Grado INT NOT NULL,
  Anio YEAR NOT NULL,
  Estado VARCHAR(20) NOT NULL DEFAULT 'activa',
  PRIMARY KEY (idMatriculas),
  CONSTRAINT fk_matricula_alumno
    FOREIGN KEY (ID_Estudiante) REFERENCES Alumnos (idAlumnos)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_matricula_curso
    FOREIGN KEY (ID_Grado) REFERENCES Curso (idCurso)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Horarios (
  idHorarios INT NOT NULL AUTO_INCREMENT,
  ID_Materia INT NOT NULL,
  ID_Profesor INT NOT NULL,
  ID_Curso INT NULL,
  Dia VARCHAR(15) NOT NULL,
  Hora_Inicio TIME NOT NULL,
  Hora_Final TIME NOT NULL,
  PRIMARY KEY (idHorarios),
  CONSTRAINT fk_horario_materia
    FOREIGN KEY (ID_Materia) REFERENCES Materia (idMateria)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_horario_profesor
    FOREIGN KEY (ID_Profesor) REFERENCES Profesores (idPROFESORES)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_horario_curso
    FOREIGN KEY (ID_Curso) REFERENCES Curso (idCurso)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE Notas (
  idNotas INT NOT NULL AUTO_INCREMENT,
  ID_Estudiante INT NOT NULL,
  ID_Materia INT NOT NULL,
  Periodo VARCHAR(20) NOT NULL,
  Valor DECIMAL(4,2) NOT NULL,
  Observaciones VARCHAR(255) NULL,
  PRIMARY KEY (idNotas),
  CONSTRAINT fk_nota_alumno
    FOREIGN KEY (ID_Estudiante) REFERENCES Alumnos (idAlumnos)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_nota_materia
    FOREIGN KEY (ID_Materia) REFERENCES Materia (idMateria)
    ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE Asistencia (
  idAsistencia INT NOT NULL AUTO_INCREMENT,
  ID_Estudiante INT NOT NULL,
  ID_Materia INT NOT NULL,
  Fecha DATE NOT NULL,
  Estado VARCHAR(20) NOT NULL,
  Observaciones VARCHAR(255) NULL,
  PRIMARY KEY (idAsistencia),
  CONSTRAINT fk_asistencia_alumno
    FOREIGN KEY (ID_Estudiante) REFERENCES Alumnos (idAlumnos)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_asistencia_materia
    FOREIGN KEY (ID_Materia) REFERENCES Materia (idMateria)
    ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE Pagos (
  idPagos INT NOT NULL AUTO_INCREMENT,
  ID_Estudiante INT NOT NULL,
  Concepto VARCHAR(100) NOT NULL,
  Monto DECIMAL(12,2) NOT NULL,
  Fecha_Emision DATE NOT NULL,
  Fecha_de_Vencimiento DATE NULL,
  Fecha_Pago DATE NULL,
  Estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
  Metodo_de_Pago VARCHAR(40) NULL,
  PRIMARY KEY (idPagos),
  CONSTRAINT fk_pago_alumno
    FOREIGN KEY (ID_Estudiante) REFERENCES Alumnos (idAlumnos)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE Usuarios (
  idUsuarios INT NOT NULL AUTO_INCREMENT,
  Nombre_de_Usuario VARCHAR(50) NOT NULL,
  ContrasenaHash VARCHAR(255) NOT NULL,
    Rol VARCHAR(50) NOT NULL,
  ID_Persona INT NULL,
  Activo TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (idUsuarios),
  UNIQUE KEY uk_usuarios_username (Nombre_de_Usuario)
) ENGINE=InnoDB;
