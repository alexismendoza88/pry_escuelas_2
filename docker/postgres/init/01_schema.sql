-- COLEGIO_APPCOL schema (PostgreSQL 16)
SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS "Asistencia" CASCADE;
DROP TABLE IF EXISTS "Notas" CASCADE;
DROP TABLE IF EXISTS "Pagos" CASCADE;
DROP TABLE IF EXISTS "Horarios" CASCADE;
DROP TABLE IF EXISTS "Matriculas" CASCADE;
DROP TABLE IF EXISTS "Materia" CASCADE;
DROP TABLE IF EXISTS "AcudienteAlumnos" CASCADE;
DROP TABLE IF EXISTS "RolVistas" CASCADE;
DROP TABLE IF EXISTS "Vistas" CASCADE;
DROP TABLE IF EXISTS "Roles" CASCADE;
DROP TABLE IF EXISTS "Usuarios" CASCADE;
DROP TABLE IF EXISTS "Alumnos" CASCADE;
DROP TABLE IF EXISTS "Profesores" CASCADE;
DROP TABLE IF EXISTS "Curso" CASCADE;

CREATE TABLE "Profesores" (
  "idPROFESORES" SERIAL PRIMARY KEY,
  "NOMBRE" VARCHAR(50) NOT NULL,
  "APELLIDO" VARCHAR(50) NOT NULL,
  "CORREO" VARCHAR(100) NOT NULL UNIQUE,
  "TELEFONO" VARCHAR(20) NULL,
  "ESPECIALIDAD" VARCHAR(100) NULL
);

CREATE TABLE "Alumnos" (
  "idAlumnos" SERIAL PRIMARY KEY,
  "NOMBRE" VARCHAR(50) NOT NULL,
  "APELLIDO" VARCHAR(50) NOT NULL,
  "FECHA_NACIMIENTO" DATE NULL,
  "DIRECCION" TEXT NULL,
  "TELEFONO" VARCHAR(20) NULL,
  "GRADO_ACTUAL" VARCHAR(20) NULL,
  "NOMBRE_ACUDIENTE" VARCHAR(100) NULL,
  "TELEFONO_ACUDIENTE" VARCHAR(20) NULL,
  "ANO_ACTUAL" VARCHAR(8) NULL
);

CREATE TABLE "Curso" (
  "idCurso" SERIAL PRIMARY KEY,
  "Grado" VARCHAR(20) NOT NULL,
  "Jornada" VARCHAR(20) NOT NULL,
  "Nivel" VARCHAR(30) NOT NULL,
  "Capacidad" INT NOT NULL DEFAULT 30
);

CREATE TABLE "Materia" (
  "idMateria" SERIAL PRIMARY KEY,
  "Codigo" VARCHAR(20) NOT NULL UNIQUE,
  "Nombre" VARCHAR(100) NOT NULL,
  "ID_Profesor" INT NULL REFERENCES "Profesores" ("idPROFESORES") ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE "Matriculas" (
  "idMatriculas" SERIAL PRIMARY KEY,
  "ID_Estudiante" INT NOT NULL REFERENCES "Alumnos" ("idAlumnos") ON UPDATE CASCADE ON DELETE RESTRICT,
  "ID_Grado" INT NOT NULL REFERENCES "Curso" ("idCurso") ON UPDATE CASCADE ON DELETE RESTRICT,
  "Anio" SMALLINT NOT NULL,
  "Estado" VARCHAR(20) NOT NULL DEFAULT 'activa'
);

CREATE TABLE "Horarios" (
  "idHorarios" SERIAL PRIMARY KEY,
  "ID_Materia" INT NOT NULL REFERENCES "Materia" ("idMateria") ON UPDATE CASCADE ON DELETE CASCADE,
  "ID_Profesor" INT NOT NULL REFERENCES "Profesores" ("idPROFESORES") ON UPDATE CASCADE ON DELETE RESTRICT,
  "ID_Curso" INT NULL REFERENCES "Curso" ("idCurso") ON UPDATE CASCADE ON DELETE SET NULL,
  "Dia" VARCHAR(15) NOT NULL,
  "Hora_Inicio" TIME NOT NULL,
  "Hora_Final" TIME NOT NULL
);

CREATE TABLE "Notas" (
  "idNotas" SERIAL PRIMARY KEY,
  "ID_Estudiante" INT NOT NULL REFERENCES "Alumnos" ("idAlumnos") ON UPDATE CASCADE ON DELETE CASCADE,
  "ID_Materia" INT NOT NULL REFERENCES "Materia" ("idMateria") ON UPDATE CASCADE ON DELETE CASCADE,
  "Periodo" VARCHAR(20) NOT NULL,
  "Valor" NUMERIC(4,2) NOT NULL,
  "Observaciones" VARCHAR(255) NULL
);

CREATE TABLE "Asistencia" (
  "idAsistencia" SERIAL PRIMARY KEY,
  "ID_Estudiante" INT NOT NULL REFERENCES "Alumnos" ("idAlumnos") ON UPDATE CASCADE ON DELETE CASCADE,
  "ID_Materia" INT NOT NULL REFERENCES "Materia" ("idMateria") ON UPDATE CASCADE ON DELETE CASCADE,
  "Fecha" DATE NOT NULL,
  "Estado" VARCHAR(20) NOT NULL,
  "Observaciones" VARCHAR(255) NULL
);

CREATE TABLE "Pagos" (
  "idPagos" SERIAL PRIMARY KEY,
  "ID_Estudiante" INT NOT NULL REFERENCES "Alumnos" ("idAlumnos") ON UPDATE CASCADE ON DELETE RESTRICT,
  "Concepto" VARCHAR(100) NOT NULL,
  "Monto" NUMERIC(12,2) NOT NULL,
  "Fecha_Emision" DATE NOT NULL,
  "Fecha_de_Vencimiento" DATE NULL,
  "Fecha_Pago" DATE NULL,
  "Estado" VARCHAR(20) NOT NULL DEFAULT 'pendiente',
  "Metodo_de_Pago" VARCHAR(40) NULL
);

CREATE TABLE "Usuarios" (
  "idUsuarios" SERIAL PRIMARY KEY,
  "Nombre_de_Usuario" VARCHAR(50) NOT NULL UNIQUE,
  "ContrasenaHash" VARCHAR(255) NOT NULL,
  "Rol" VARCHAR(50) NOT NULL,
  "ID_Persona" INT NULL,
  "Activo" BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE "Roles" (
  "idRoles" SERIAL PRIMARY KEY,
  "Codigo" VARCHAR(50) NOT NULL UNIQUE,
  "Nombre" VARCHAR(80) NOT NULL,
  "Descripcion" VARCHAR(255) NULL,
  "Activo" BOOLEAN NOT NULL DEFAULT TRUE,
  "EsSistema" BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE "Vistas" (
  "idVistas" SERIAL PRIMARY KEY,
  "Codigo" VARCHAR(50) NOT NULL UNIQUE,
  "Nombre" VARCHAR(80) NOT NULL,
  "Ruta" VARCHAR(80) NOT NULL,
  "Orden" INT NOT NULL DEFAULT 0,
  "SoloAdmin" BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE "RolVistas" (
  "ID_Rol" INT NOT NULL REFERENCES "Roles" ("idRoles") ON UPDATE CASCADE ON DELETE CASCADE,
  "ID_Vista" INT NOT NULL REFERENCES "Vistas" ("idVistas") ON UPDATE CASCADE ON DELETE CASCADE,
  PRIMARY KEY ("ID_Rol", "ID_Vista")
);

CREATE TABLE "AcudienteAlumnos" (
  "ID_Usuario" INT NOT NULL REFERENCES "Usuarios" ("idUsuarios") ON UPDATE CASCADE ON DELETE CASCADE,
  "ID_Alumno" INT NOT NULL REFERENCES "Alumnos" ("idAlumnos") ON UPDATE CASCADE ON DELETE CASCADE,
  PRIMARY KEY ("ID_Usuario", "ID_Alumno")
);
